import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { Engine } from "../engine/engine.js";
import { PlannerMemory } from "../planning/memory.js";
import { repoById, TaskItem } from "./dataset.js";
import { oracleVersionHash } from "./gt.js";
import {
  conventionalFindCallees,
  conventionalFindCallers,
  conventionalImpact,
} from "./conventional.js";

/**
 * One experimental arm, in its own process:
 *   (repository, system, workload) -> per-task answers + measured cost.
 *
 * Isolating each arm in a process is what makes peak RSS and CPU attributable,
 * and stops one arm's caches from warming another's.
 */

type System = "adaptive" | "exhaustive" | "required-only" | "conventional";

function arg(name: string, fallback?: string): string {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0) {
    if (fallback !== undefined) return fallback;
    throw new Error(`missing --${name}`);
  }
  return process.argv[i + 1]!;
}

const repoId = arg("repo");
const system = arg("system") as System;
const workload = arg("workload", "cold") as "cold" | "warm";
const out = arg("out");
const spec = repoById(repoId);
const gtPath = path.resolve(path.dirname(new URL(import.meta.url).pathname), `../../results/gt-${repoId}.json`);
const gtFile = JSON.parse(fs.readFileSync(gtPath, "utf8")) as {
  tasks: TaskItem[];
  provenance?: { oracleVersionHash: string; repositorySnapshot: { sha: string | null } };
};

// Fail loudly rather than silently score against a since-patched oracle (see
// gt.ts's PROVENANCE_SOURCE_FILES comment). A gt-*.json written before this
// provenance block existed has no `provenance` field at all — that is
// unambiguously stale too, not merely "unknown", since it predates the oracle
// split entirely.
if (!gtFile.provenance) {
  throw new Error(`${gtPath} has no provenance stamp; regenerate ground truth (npx tsx src/experiment/gt.ts) before scoring`);
}
const currentHash = oracleVersionHash();
if (gtFile.provenance.oracleVersionHash !== currentHash) {
  throw new Error(
    `${gtPath} was generated by a different oracle version ` +
      `(gt: ${gtFile.provenance.oracleVersionHash.slice(0, 12)}, current: ${currentHash.slice(0, 12)}). ` +
      `Regenerate ground truth before scoring, or this arm's numbers will silently reflect the old oracle.`,
  );
}

interface TaskRecord {
  type: string;
  symbol: string;
  answer: string[];
  /** answers the system reports as uncertain rather than asserting */
  hedged: string[];
  wallMs: number;
  analysesRun: number;
  notRun: number;
  uncertainty: number | null;
  sufficient: boolean | null;
  stopReason: string | null;
  /** files reused from Engine's persistent disk cache for this task's Engine instance */
  restoredFromCache: number;
}

/**
 * Cache isolation.
 *
 * `Engine` persists analysis facts to a disk cache (`$SIE_CACHE_DIR`/
 * `~/.sie-cache`) keyed only by the repository's absolute path (see
 * src/knowledge/persist.ts). Every (repo, system, workload) arm queries the
 * *same* repo path, each in its own process (see runner.ts) — so with the
 * global default cache dir, whichever arm runs first for a repo persists a
 * "fully analyzed" snapshot to disk, and every later arm for that same repo
 * hydrates that snapshot and thinks its required analyses are already
 * satisfied. That silently zeroes `analysesRun` for nearly every task
 * regardless of system — a measurement defect, not a planner property.
 *
 * A single cache directory per arm (fixed at process start) stops *cross-arm*
 * leakage, but "cold" is supposed to mean every task starts from nothing: if
 * the whole arm shares one cache dir, task 1's cold Engine writes an
 * analyzed snapshot to disk on exit/persist, and task 2's "cold" Engine
 * (same dir) silently rehydrates it — cross-task contamination *within* the
 * arm, invisible unless something actually checks `restoredFromCache`. So:
 *
 *   cold: a fresh `mkdtemp` cache dir per task, destroyed immediately after
 *         that task completes — nothing can leak in from, or out to,
 *         anything else, including this arm's own earlier tasks.
 *   warm: one isolated cache dir for the whole arm, so legitimate
 *         intra-arm reuse across tasks (what "warm" is meant to measure)
 *         still works, but it's still a fresh directory this run created,
 *         not a stale directory some earlier run left behind.
 *
 * Either way, a task whose Engine reports `restoredFromCache !== 0` when
 * none was expected throws immediately instead of silently producing a
 * "warm-looking" cold number.
 */
const arenaCacheRoot = fs.mkdtempSync(path.join(os.tmpdir(), `sie-arm-cache-${repoId}-${system}-${workload}-`));
process.on("exit", () => fs.rmSync(arenaCacheRoot, { recursive: true, force: true }));

async function main() {
  const records: TaskRecord[] = [];
  const memory = new PlannerMemory();
  let warmEngine: Engine | null = null;
  let warmCacheDir: string | null = null;
  if (workload === "warm") {
    warmCacheDir = path.join(arenaCacheRoot, "warm");
    fs.mkdirSync(warmCacheDir, { recursive: true });
  }

  const onlyTypes = process.env.ONLY_TASK_TYPES ? new Set(process.env.ONLY_TASK_TYPES.split(",")) : null;
  let taskList = onlyTypes ? gtFile.tasks.filter((t) => onlyTypes.has(t.type)) : gtFile.tasks;

  // Resume affordance: if `out` already exists and is marked partial (from
  // a prior invocation of this exact arm that got killed by an external
  // time budget), pick up after the tasks it already completed instead of
  // redoing them. Only trusts a partial file for the same repo/system/
  // workload, so it can't silently splice in results from a different arm.
  if (process.env.RESUME_PARTIAL === "1" && fs.existsSync(out)) {
    const prior = JSON.parse(fs.readFileSync(out, "utf8"));
    // Merge regardless of the prior file's own `partial` flag: that flag
    // describes whether *its own* task subset finished, not whether this
    // invocation's (possibly different) ONLY_TASK_TYPES subset is covered.
    // Always carry forward whatever tasks it already has and only compute
    // what's still missing.
    if (prior.repo === repoId && prior.system === system && prior.workload === workload) {
      const done = new Set((prior.records as TaskRecord[]).map((r) => `${r.type}:${r.symbol}`));
      for (const r of prior.records as TaskRecord[]) records.push(r);
      taskList = taskList.filter((t) => !done.has(`${t.type}:${t.symbol}`));
    }
  }

  // Flush after every task, not just at the end. This is a harness-only
  // affordance for slow arms (a fresh Engine per cold task on a large repo
  // is expensive) — it changes nothing about what's measured for any task
  // that completes; it only means a run that's killed externally leaves a
  // valid, explicitly-marked-partial JSON instead of nothing.
  function flush() {
    const partial = records.length < gtFile.tasks.length;
    const usage = process.resourceUsage();
    fs.writeFileSync(
      out,
      JSON.stringify(
        {
          repo: repoId,
          system,
          workload,
          records,
          partial,
          process: {
            userCpuMs: usage.userCPUTime / 1000,
            systemCpuMs: usage.systemCPUTime / 1000,
            peakRssBytes: usage.maxRSS * 1024,
            wallMsTotal: records.reduce((a, r) => a + r.wallMs, 0),
          },
        },
        null,
        2,
      ),
    );
  }

  for (const task of taskList) {
    const t0 = process.hrtime.bigint();
    let answer: string[] = [];
    let hedged: string[] = [];
    let analysesRun = 0;
    let notRun = 0;
    let uncertainty: number | null = null;
    let sufficient: boolean | null = null;
    let stopReason: string | null = null;
    let restoredFromCache = 0;
    let coldTaskCacheDir: string | null = null;

    try {
      if (system === "conventional") {
        if (task.type === "FindCallers") answer = conventionalFindCallers(spec.root, task.symbol);
        else if (task.type === "FindCallees") answer = conventionalFindCallees(spec.root, task.symbol);
        else {
          // The conventional baseline is a single one-hop regex import
          // scan (see conventional.ts) — it doesn't distinguish import vs.
          // call vs. test impact any more than a typical non-type-aware
          // pipeline would. It answers the same way for all three impact
          // task types; that's the honest baseline, not a shortcut.
          const impact = conventionalImpact(spec.root, task.symbol);
          answer = task.type === "TestImpact" ? impact.filter((f) => /(^|\/)tests?\//.test(f) || /\.(test|spec)\.[cm]?[jt]sx?$/.test(f)) : impact;
        }
      } else {
        let engine: Engine;
        if (workload === "warm") {
          if (!warmEngine) warmEngine = new Engine(spec.root, { plannerMode: system as never, plannerMemory: memory, cacheDir: warmCacheDir });
          engine = warmEngine;
        } else {
          coldTaskCacheDir = fs.mkdtempSync(path.join(arenaCacheRoot, "cold-"));
          engine = new Engine(spec.root, { plannerMode: system as never, plannerMemory: memory, cacheDir: coldTaskCacheDir });
        }
        restoredFromCache = engine.restoredFromCache;
        if (workload === "cold" && restoredFromCache !== 0) {
          throw new Error(
            `cache isolation violation: cold task ${task.type}:${task.symbol} restored ${restoredFromCache} file(s) from a cache dir that was just created empty`,
          );
        }

        if (task.type === "FindCallers") {
          const o = await engine.findCallers(task.symbol);
          // Verification-gated: only confirmed (statically-pinned, EXACT
          // resolution) call sites count as the scored answer. Interface-
          // typed/virtual-dispatch sites are real findings but are hedges,
          // not confirmed callers — reported separately as `hedged` so a
          // recall shortfall from excluding them is visible, not silently
          // absorbed into the primary score.
          answer = o.result.confirmed.map((c) => `${c.callSite.file}:${c.callSite.line}`);
          hedged = o.result.possible.map((c) => `${c.callSite.file}:${c.callSite.line}`);
          uncertainty = o.uncertainty.value;
          analysesRun = o.costByAnalysis.length;
          notRun = o.notRun.length;
          sufficient = o.sufficient;
          stopReason = o.stopReason;
        } else if (task.type === "FindCallees") {
          const o = await engine.findCallees(task.symbol);
          // The independent oracle (oracles-ext.ts calleeOracle) only has a bare
          // identifier/property-access name to go on — it has no type checker
          // pass that could qualify a call by its declaring container. The
          // engine's `calleeName` is intentionally more precise ("Class.method",
          // and one entry per virtual-dispatch implementation), so comparing it
          // to the oracle verbatim scores every qualified/polymorphic answer as
          // wrong even when it agrees. Normalize to the trailing name component
          // — the oracle's granularity — for scoring purposes only.
          const bare = (name: string) => name.split(".").pop()!;
          // Verification-gated, same rationale as FindCallers above:
          // confirmed-only is the scored answer, possible (virtual-dispatch
          // implementations that may or may not run) is reported as hedged.
          answer = o.result.confirmed.map((c) => bare(c.calleeName));
          hedged = o.result.possible.map((c) => bare(c.calleeName));
          uncertainty = o.uncertainty.value;
          analysesRun = o.costByAnalysis.length;
          notRun = o.notRun.length;
          sufficient = o.sufficient;
          stopReason = o.stopReason;
        } else if (task.type === "TestImpact") {
          // Purpose-built engine capability for this notion of impact
          // (reverse CALLS-graph reachability from test files), rather
          // than filtering impactOfChange's affectedFiles down to test
          // paths — the latter would just inherit impactOfChange's own
          // depth bound and CALLS/REFERENCES conflation as an artifact of
          // reuse, not measure the engine's actual test-impact reasoning.
          const o = await engine.whichTestsExercise(task.symbol);
          const files = new Set([...o.result.statically, ...o.result.runtimeConfirmed].map((f) => f.file));
          answer = [...files];
          uncertainty = o.uncertainty.value;
          analysesRun = o.costByAnalysis.length;
          notRun = o.notRun.length;
          sufficient = o.sufficient;
          stopReason = o.stopReason;
        } else if (task.type === "ImportImpact") {
          // Dedicated mechanism: resolve the symbol to its declaring
          // module, then walk the barrel-aware reverse import/re-export
          // graph (`dependentsOf`) — independent of `impactOfChange`'s
          // call-graph traversal. See engine.ts's `importImpact` doc
          // comment. Scoring this separately from CallImpact is what makes
          // the two failure modes legible: a CallImpact shortfall is the
          // call-graph mechanism failing on its own terms, an ImportImpact
          // shortfall is a gap in import/re-export-closure reasoning.
          const o = await engine.importImpact(task.symbol);
          answer = o.result.affectedFiles;
          uncertainty = o.uncertainty.value;
          analysesRun = o.costByAnalysis.length;
          notRun = o.notRun.length;
          sufficient = o.sufficient;
          stopReason = o.stopReason;
        } else {
          // CallImpact: impactOfChange's reverse CALLS/REFERENCES
          // traversal, bounded to maxDepth (default 4) — "what could
          // actually execute differently", not "what could observe an
          // export change" (that's ImportImpact, above).
          const o = await engine.impactOfChange(task.symbol);
          // `affectedFiles` entries are already repository-relative (they come
          // from SourceLocation.file, which locOf() built via rel(root, ...) at
          // acquisition time). Re-relativizing an already-relative path against
          // the absolute repo root here resolves it against process.cwd()
          // instead, producing nonsense like "../../../src/foo.ts" that can
          // never match the ground-truth's "src/foo.ts".
          answer = o.result.affectedFiles;
          uncertainty = o.uncertainty.value;
          analysesRun = o.costByAnalysis.length;
          notRun = o.notRun.length;
          sufficient = o.sufficient;
          stopReason = o.stopReason;
        }
      }
    } catch (e) {
      stopReason = `error: ${(e as Error).message}`;
    } finally {
      if (coldTaskCacheDir) fs.rmSync(coldTaskCacheDir, { recursive: true, force: true });
    }
    const wallMs = Number(process.hrtime.bigint() - t0) / 1e6;
    records.push({
      type: task.type,
      symbol: task.symbol,
      answer: [...new Set(answer)].sort(),
      hedged: [...new Set(hedged)].sort(),
      wallMs,
      analysesRun,
      notRun,
      uncertainty,
      sufficient,
      stopReason,
      restoredFromCache,
    });
    flush();
  }
  flush();
}

void main();
