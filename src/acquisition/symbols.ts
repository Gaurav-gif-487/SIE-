import fs from "node:fs";
import ts from "typescript";
import { EvidenceStatus, Resolution, entityId } from "../canonical/model.js";
import { KnowledgeStore } from "../knowledge/store.js";
import { Counters } from "../cost/measure.js";
import { ProgramHandle, fileHashes, rel } from "./program.js";
import {
  containerName,
  declarationId,
  declarationKind,
  declarationName,
  isExported,
  locOf,
  moduleIdFor,
  resolveImportTarget,
} from "./ast-utils.js";

/**
 * ParseSource: cheap crystallization level 1.
 * Repository -> files -> modules. No symbols, no types.
 */
export function acquireFilesAndModules(
  handle: ProgramHandle,
  store: KnowledgeStore,
  counters: Counters,
): void {
  const root = handle.root;
  store.putEntity({
    id: entityId("Repository", rel(root, root) || "."),
    kind: "Repository",
    name: root,
    attributes: { tsconfig: handle.configPath ? rel(root, handle.configPath) : null },
  });

  const hashes = fileHashes(
    handle.sourceFiles.map((sf) => sf.fileName),
    root,
  );

  for (const sf of handle.sourceFiles) {
    const file = rel(root, sf.fileName);
    const lineCount = sf.getLineStarts().length;
    const fileEntity = store.putEntity({
      id: entityId("File", file),
      kind: "File",
      name: file,
      location: { file, line: 1, column: 1 },
      attributes: { lines: lineCount, bytes: sf.text.length },
    });
    const hash = hashes.get(file);
    if (hash) store.recordFileHash(file, hash);
    store.addEvidence({
      fact: `file ${file} exists and parses as ${sf.languageVariant === ts.LanguageVariant.JSX ? "jsx" : "standard"} source`,
      source: "ts.createSourceFile",
      sourceType: "typescript-compiler",
      location: { file, line: 1, column: 1 },
      revision: store.revision,
      derivation: "source-file-parsed",
      status: EvidenceStatus.RESOLVED,
      producedBy: "ParseSource",
      supports: [fileEntity.id],
    });

    const moduleEntity = store.putEntity({
      id: moduleIdFor(file),
      kind: "Module",
      name: file,
      location: { file, line: 1, column: 1 },
      attributes: { isModule: ts.isExternalModule(sf) },
    });
    store.putRelation({
      kind: "DECLARES",
      from: fileEntity.id,
      to: moduleEntity.id,
      resolution: Resolution.EXACT,
      location: { file, line: 1, column: 1 },
      attributes: {},
    });
    counters.filesProcessed += 1;

    // imports / exports: still cheap, purely syntactic + module resolution
    for (const stmt of sf.statements) {
      if (ts.isImportDeclaration(stmt) && ts.isStringLiteral(stmt.moduleSpecifier)) {
        const spec = stmt.moduleSpecifier.text;
        const target = resolveImportTarget(sf, spec, handle.program, root);
        const location = locOf(sf, stmt, root);
        const relation = store.putRelation({
          kind: "IMPORTS",
          from: moduleEntity.id,
          to: target ? moduleIdFor(target) : null,
          resolution: target ? Resolution.EXACT : Resolution.UNRESOLVED,
          location,
          attributes: { specifier: spec, external: target === null },
        });
        store.addEvidence({
          fact: `${file} imports "${spec}"${target ? ` resolved to ${target}` : " (outside repository or unresolvable)"}`,
          source: "ts.resolveModuleName",
          sourceType: "typescript-compiler",
          location,
          revision: store.revision,
          derivation: "import-declaration",
          status: target ? EvidenceStatus.RESOLVED : EvidenceStatus.PARTIAL,
          producedBy: "ParseSource",
          supports: [relation.id],
        });
      }
      if (ts.isExportDeclaration(stmt) || ts.isExportAssignment(stmt)) {
        const location = locOf(sf, stmt, root);
        const spec =
          ts.isExportDeclaration(stmt) && stmt.moduleSpecifier && ts.isStringLiteral(stmt.moduleSpecifier)
            ? stmt.moduleSpecifier.text
            : null;
        const target = spec ? resolveImportTarget(sf, spec, handle.program, root) : null;
        store.putRelation({
          kind: "EXPORTS",
          from: moduleEntity.id,
          to: target ? moduleIdFor(target) : null,
          resolution: target ? Resolution.EXACT : Resolution.PARTIAL,
          location,
          attributes: { reExportOf: spec },
        });
      }
    }
  }

  // Detect generated code, a real residual-risk factor.
  for (const sf of handle.sourceFiles) {
    const head = sf.text.slice(0, 400);
    if (/@generated|AUTO-GENERATED|Code generated by|DO NOT EDIT/i.test(head)) {
      store.addUnknown({
        kind: "generated-code",
        location: { file: rel(root, sf.fileName), line: 1, column: 1 },
        detail: "file header marks it as generated; upstream generator not analyzed",
      });
    }
  }

  // Files on disk the program refused to include are missing knowledge.
  for (const file of hashes.keys()) {
    if (!store.hasEntity(entityId("File", file))) {
      store.addUnknown({
        kind: "unparsed-file",
        location: { file, line: 1, column: 1 },
        detail: "file discovered on disk but not part of the TypeScript program",
      });
    }
  }
}

/**
 * ResolveSymbols: crystallization level 2 (module -> symbols).
 */
export function acquireSymbols(handle: ProgramHandle, store: KnowledgeStore, counters: Counters): void {
  const root = handle.root;
  for (const sf of handle.sourceFiles) {
    const file = rel(root, sf.fileName);
    const moduleId = moduleIdFor(file);
    const visit = (node: ts.Node): void => {
      const kind = declarationKind(node);
      const name = declarationName(node);
      if (kind && name) {
        const id = declarationId(kind, node, name, root);
        const location = locOf(sf, node, root);
        const owner = containerName(node);
        const entity = store.putEntity({
          id,
          kind,
          name,
          location,
          attributes: {
            container: owner,
            exported: isExported(node),
            file,
            static: ts.canHaveModifiers(node)
              ? Boolean(ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.StaticKeyword))
              : false,
            abstract: ts.canHaveModifiers(node)
              ? Boolean(ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.AbstractKeyword))
              : false,
            declarationOnly: ts.isMethodSignature(node),
          },
        });
        store.putRelation({
          kind: "DECLARES",
          from: moduleId,
          to: entity.id,
          resolution: Resolution.EXACT,
          location,
          attributes: {},
        });
        store.addEvidence({
          fact: `${owner ? `${owner}.` : ""}${name} is declared as ${kind} at ${location.file}:${location.line}`,
          source: "ts.SourceFile AST walk",
          sourceType: "typescript-compiler",
          location,
          revision: store.revision,
          derivation: `declaration:${ts.SyntaxKind[node.kind]}`,
          status: EvidenceStatus.RESOLVED,
          producedBy: "ResolveSymbols",
          supports: [entity.id],
        });
        counters.symbolsProcessed += 1;
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(sf, visit);
    counters.filesProcessed += 1;
  }
}

/**
 * ResolveTypes: attach checker-derived type strings and signatures to symbols.
 * This is what makes call resolution type-aware rather than name-based.
 */
export function acquireTypes(handle: ProgramHandle, store: KnowledgeStore, counters: Counters): void {
  const { checker, root } = handle;
  for (const sf of handle.sourceFiles) {
    const visit = (node: ts.Node): void => {
      const kind = declarationKind(node);
      const name = declarationName(node);
      if (kind && name) {
        const id = declarationId(kind, node, name, root);
        const entity = store.getEntity(id);
        if (entity) {
          const symbol = checker.getSymbolAtLocation((node as ts.NamedDeclaration).name ?? node);
          const type = symbol
            ? checker.getTypeOfSymbolAtLocation(symbol, node)
            : checker.getTypeAtLocation(node);
          const signatures = type.getCallSignatures();
          entity.attributes.typeText = checker.typeToString(type);
          entity.attributes.returnType =
            signatures.length > 0 ? checker.typeToString(signatures[0]!.getReturnType()) : null;
          entity.attributes.parameterTypes =
            signatures.length > 0
              ? signatures[0]!
                  .getParameters()
                  .map((p) => `${p.name}: ${checker.typeToString(checker.getTypeOfSymbolAtLocation(p, node))}`)
                  .join(", ")
              : null;
          store.addEvidence({
            fact: `${name} has type ${checker.typeToString(type)}`,
            source: "ts.TypeChecker#getTypeOfSymbolAtLocation",
            sourceType: "typescript-compiler",
            location: locOf(sf, node, root),
            revision: store.revision,
            derivation: "checker-type-of-declaration",
            status: EvidenceStatus.RESOLVED,
            producedBy: "ResolveTypes",
            supports: [id],
          });
          counters.symbolsProcessed += 1;
        }
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(sf, visit);
    counters.filesProcessed += 1;
  }
}

/**
 * AnalyzeInheritance: EXTENDS / IMPLEMENTS edges, used later to expand
 * interface-declared call targets into concrete implementations.
 */
export function acquireInheritance(handle: ProgramHandle, store: KnowledgeStore, counters: Counters): void {
  const { checker, root } = handle;
  for (const sf of handle.sourceFiles) {
    const visit = (node: ts.Node): void => {
      if ((ts.isClassDeclaration(node) || ts.isInterfaceDeclaration(node)) && node.name) {
        const kind = ts.isClassDeclaration(node) ? "Class" : "Interface";
        const fromId = declarationId(kind, node, node.name.text, root);
        for (const clause of node.heritageClauses ?? []) {
          const relKind = clause.token === ts.SyntaxKind.ExtendsKeyword ? "EXTENDS" : "IMPLEMENTS";
          for (const expr of clause.types) {
            const symbol = checker.getSymbolAtLocation(expr.expression);
            const resolvedSymbol =
              symbol && symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
            const decl = resolvedSymbol?.declarations?.find(
              (d) => ts.isClassDeclaration(d) || ts.isInterfaceDeclaration(d),
            );
            const targetId =
              decl && (decl as ts.ClassDeclaration).name
                ? declarationId(
                    ts.isClassDeclaration(decl) ? "Class" : "Interface",
                    decl,
                    (decl as ts.ClassDeclaration).name!.text,
                    root,
                  )
                : null;
            const location = locOf(sf, expr, root);
            const relation = store.putRelation({
              kind: relKind,
              from: fromId,
              to: targetId,
              resolution: targetId ? Resolution.EXACT : Resolution.UNRESOLVED,
              location,
              attributes: { text: expr.getText(sf) },
            });
            store.addEvidence({
              fact: `${node.name.text} ${relKind.toLowerCase()} ${expr.getText(sf)}`,
              source: "ts.TypeChecker#getSymbolAtLocation (heritage clause)",
              sourceType: "typescript-compiler",
              location,
              revision: store.revision,
              derivation: "heritage-clause",
              status: targetId ? EvidenceStatus.RESOLVED : EvidenceStatus.PARTIAL,
              producedBy: "AnalyzeInheritance",
              supports: [relation.id],
            });
            if (!targetId) {
              store.addUnknown({
                kind: "unsupported-syntax",
                location,
                detail: `heritage target "${expr.getText(sf)}" is declared outside the analyzed repository`,
              });
            }
          }
        }
        counters.symbolsProcessed += 1;
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(sf, visit);
    counters.filesProcessed += 1;
  }
}

export function readTextSafe(file: string): string | null {
  try {
    return fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
}
